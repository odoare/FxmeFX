/*
    tape_measure.cpp

    Measures FxmeTape's signal path, from the FxmeTools core headers it is
    built on (TapeHysteresis.h, TapeEq.h, Biquad.h), with no JUCE: the whole
    chain runs at 96 kHz, which stands in for the plugin's oversampling
    (the plugin runs only the tape and the head loss oversampled; the
    linear stages around them are the same at either rate).

    Build and run (from the FxmeFX root, FxmeTools as a sibling clone):

        g++ -std=c++17 -O2 -I ../FxmeTools/core doc/Tape/tape_measure.cpp -o /tmp/tape_measure
        /tmp/tape_measure > doc/Tape/tape_results.md

    Three measurements, written as Markdown tables:

      1. Small-signal frequency response (-40 dBFS) per speed and EQ.
      2. THD, and the 3rd and 2nd harmonics, against level at 1 kHz.
      3. Output level against input level at 1 kHz and 10 kHz: the
         pre-emphasis should make the highs compress first.
*/

#include <FxmeTools/dsp/Biquad.h>
#include <FxmeTools/dsp/TapeEq.h>
#include <FxmeTools/dsp/TapeHysteresis.h>

#include <cmath>
#include <complex>
#include <cstdio>
#include <vector>

namespace
{
    constexpr double fs = 96000.0;
    constexpr double pi = 3.141592653589793;
    using namespace fxme::tape;
    using TapeType = fxme::TapeHysteresis::TapeType;

    /** The plugin's chain, one channel, Drive 0 dB, Saturation 50 %, Auto gain. */
    struct Chain
    {
        EmphasisFilter pre, de;
        fxme::TapeHysteresis tape;
        fxme::Biquad loss, bump, dip, lowCut, shelf;
        float in = 1.0f, norm = 1.0f;

        Chain (Speed s, EqStandard e, TapeType type, float bias)
        {
            pre.setup (s, e, true, fs);
            de.setup (s, e, false, fs);
            tape.prepare (fs);
            const auto p = fxme::TapeHysteresis::paramsFor (type, bias);
            tape.setParams (p);
            const float headroom = std::pow (10.0f, fxme::TapeHysteresis::headroomDb (type) / 20.0f);
            in = 1.0f / headroom;
            norm = headroom / fxme::TapeHysteresis::approxGain (p);
            loss.c = fxme::BiquadCoeffs::lowpass (fs, (float) std::fmin (headLossCutoffHz (s), 0.45 * fs), 0.7071f);
            const auto hb = headBumpFor (s);
            bump.c = fxme::BiquadCoeffs::peaking (fs, hb.freqHz, hb.q, hb.gainDb);
            dip.c = fxme::BiquadCoeffs::peaking (fs, hb.dipHz, hb.dipQ, hb.dipDb);
            lowCut.c = fxme::BiquadCoeffs::highpass (fs, hb.lowCutHz, 0.7071f);
            shelf.c = fxme::BiquadCoeffs::highShelf (fs, 8000.0f, -6.0f * (bias - 0.5f));
        }

        float process (float x)
        {
            float y = loss.processSample (tape.process (pre.process (x * in)));
            y = de.process (y * norm);
            return shelf.processSample (lowCut.processSample (dip.processSample (bump.processSample (y))));
        }
    };

    std::vector<float> runSine (Chain& c, double amp, double hz, int n)
    {
        std::vector<float> y ((size_t) n);
        for (int i = 0; i < n; ++i)
            y[(size_t) i] = c.process ((float) (amp * std::sin (2.0 * pi * hz * i / fs)));
        return y;
    }

    double harmonic (const std::vector<float>& y, double f0, int h, size_t n)
    {
        std::complex<double> acc { 0.0, 0.0 };
        const size_t start = y.size() - n;
        for (size_t i = 0; i < n; ++i)
            acc += (double) y[start + i] * std::polar (1.0, -2.0 * pi * f0 * h * (double) i / fs);
        return 2.0 * std::abs (acc) / (double) n;
    }

    double db (double x) { return 20.0 * std::log10 (x > 1.0e-12 ? x : 1.0e-12); }

    const char* speedName (Speed s) { return s == Speed::ips7_5 ? "7.5 ips" : (s == Speed::ips15 ? "15 ips" : "30 ips"); }
}

int main()
{
    std::printf ("# FxmeTape: measurements\n\n");
    std::printf ("Generated by `doc/Tape/tape_measure.cpp` (the FxmeTools core code, at 96 kHz). "
                 "Modern tape, calibrated bias, Drive 0 dB, Saturation 50 %%, Auto gain.\n\n");

    std::printf ("## 1. Small-signal response (-40 dBFS), dB\n\n");
    const double freqs[] { 20, 30, 45, 65, 100, 160, 250, 1000, 5000, 10000, 15000, 20000 };
    std::printf ("| Speed, EQ |");
    for (double f : freqs) std::printf (" %g Hz |", f);
    std::printf ("\n|---|");
    for (size_t i = 0; i < sizeof (freqs) / sizeof (freqs[0]); ++i) std::printf ("---:|");
    std::printf ("\n");
    for (auto s : { Speed::ips7_5, Speed::ips15, Speed::ips30 })
        for (auto e : { EqStandard::nab, EqStandard::iec })
        {
            if (s == Speed::ips30 && e == EqStandard::iec)
                continue;   // the same as NAB (AES)
            std::printf ("| %s, %s |", speedName (s), s == Speed::ips30 ? "AES" : (e == EqStandard::nab ? "NAB" : "IEC"));
            for (double f : freqs)
            {
                Chain c (s, e, TapeType::modern, 0.5f);
                const int periods = (int) std::ceil (f * 0.5);   // half a second at least
                const int n = (int) (fs / f * periods) + (int) fs;
                const auto y = runSine (c, 0.01, f, n);
                const size_t m = (size_t) (fs / f * periods);
                std::printf (" %+.1f |", db (harmonic (y, f, 1, m) / 0.01));
            }
            std::printf ("\n");
        }

    std::printf ("\n## 2. Distortion at 1 kHz against level (15 ips NAB)\n\n");
    std::printf ("| Input, dBFS | Output, dBFS | THD, %% | H2, dB | H3, dB | H5, dB |\n|---:|---:|---:|---:|---:|---:|\n");
    for (double lvl : { -30.0, -24.0, -18.0, -12.0, -6.0, 0.0, 6.0 })
    {
        Chain c (Speed::ips15, EqStandard::nab, TapeType::modern, 0.5f);
        const double amp = std::pow (10.0, lvl / 20.0);
        const auto y = runSine (c, amp, 1000.0, 96000);
        const size_t n = 48000;
        const double h1 = harmonic (y, 1000.0, 1, n);
        double sum = 0.0;
        for (int h = 2; h <= 9; ++h) sum += std::pow (harmonic (y, 1000.0, h, n), 2.0);
        std::printf ("| %+.0f | %+.1f | %.2f | %.1f | %.1f | %.1f |\n", lvl, db (h1), 100.0 * std::sqrt (sum) / h1,
                     db (harmonic (y, 1000.0, 2, n) / h1), db (harmonic (y, 1000.0, 3, n) / h1),
                     db (harmonic (y, 1000.0, 5, n) / h1));
    }

    std::printf ("\n## 3. Compression: output against input at 1 kHz and 10 kHz (gain change from -30 dBFS, dB)\n\n");
    std::printf ("| Input, dBFS | 1 kHz, NAB 15 | 10 kHz, NAB 15 | 1 kHz, NAB 7.5 | 10 kHz, NAB 7.5 |\n|---:|---:|---:|---:|---:|\n");
    auto gainAt = [] (Speed s, double hz, double lvl)
    {
        Chain c (s, EqStandard::nab, TapeType::modern, 0.5f);
        const double amp = std::pow (10.0, lvl / 20.0);
        const auto y = runSine (c, amp, hz, 96000);
        return db (harmonic (y, hz, 1, 48000) / amp);
    };
    for (double lvl : { -30.0, -18.0, -12.0, -6.0, 0.0, 6.0 })
        std::printf ("| %+.0f | %+.1f | %+.1f | %+.1f | %+.1f |\n", lvl,
                     gainAt (Speed::ips15, 1000.0, lvl) - gainAt (Speed::ips15, 1000.0, -30.0),
                     gainAt (Speed::ips15, 10000.0, lvl) - gainAt (Speed::ips15, 10000.0, -30.0),
                     gainAt (Speed::ips7_5, 1000.0, lvl) - gainAt (Speed::ips7_5, 1000.0, -30.0),
                     gainAt (Speed::ips7_5, 10000.0, lvl) - gainAt (Speed::ips7_5, 10000.0, -30.0));
    return 0;
}
